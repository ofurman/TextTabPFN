"""Synthetic scene generator (decision D-06).

A scene is a random-DAG structural causal model with 6-15 continuous observed
features and a binary target ``y = 1[z > t]`` from a latent outcome ``z``.
Every observed column has exactly one role:

- ``mb``: in the Markov blanket of the outcome (a direct parent of ``z`` or a
  direct child of ``z``);
- ``irrelevant``: generated by a separate random DAG, independent of ``y``;
- ``measure``: one of a group of 2-3 noisy measurements of one hidden
  (unobserved) cause of ``z``; ``group`` identifies the hidden cause.

Six mechanism families = 3 mechanism classes x 2 noise regimes. Families 0-3
are used for training and dev scenes; families 4-5 (an unseen mechanism
class) are held out for evaluation.

A scene is a pure function of ``(family, seed)``. The seed ranges below are
disjoint, so stages never reuse one another's scenes.
"""

from __future__ import annotations

import dataclasses
from typing import Literal

import numpy as np

# --- Families -------------------------------------------------------------------

MECHANISMS = ("linear", "tanh", "interaction")
NOISE_REGIMES = ("gaussian", "heavy")
# family id -> (mechanism class, noise regime)
FAMILIES: dict[int, tuple[str, str]] = {
    0: ("linear", "gaussian"),
    1: ("linear", "heavy"),
    2: ("tanh", "gaussian"),
    3: ("tanh", "heavy"),
    4: ("interaction", "gaussian"),
    5: ("interaction", "heavy"),
}
TRAIN_FAMILIES = (0, 1, 2, 3)
HELDOUT_FAMILIES = (4, 5)

# --- Seed ranges (disjoint by construction) -------------------------------------

# Training episodes (stage 3) draw scene seeds from [0, 1_000_000).
TRAIN_SEED_RANGE = (0, 1_000_000)
# Dev scenes (stage 1 capacity, stage 3 validation) use [1_000_000, 1_100_000).
DEV_SEED_RANGE = (1_000_000, 1_100_000)
# Held-out-family evaluation scenes (stages 4-5) use [2_000_000, 2_100_000).
EVAL_SEED_RANGE = (2_000_000, 2_100_000)

# Rows drawn once per scene to fix node standardisation and the threshold.
_CALIBRATION_ROWS = 4096

Role = Literal["mb", "irrelevant", "measure"]


def dev_scene_specs(num_scenes: int) -> list[tuple[int, int]]:
    """``(family, seed)`` for the first ``num_scenes`` dev scenes (families 0-3)."""
    start = DEV_SEED_RANGE[0]
    if num_scenes > DEV_SEED_RANGE[1] - start:
        raise ValueError("too many dev scenes for the dev seed range")
    return [(TRAIN_FAMILIES[i % 4], start + i) for i in range(num_scenes)]


@dataclasses.dataclass(frozen=True)
class ColumnRole:
    """Role of one observed column (column order = feature order in ``X``)."""

    role: Role
    group: int | None = None  # hidden-cause id for ``measure`` columns
    relation: Literal["parent", "child"] | None = None  # for ``mb`` columns


@dataclasses.dataclass
class _Node:
    """One SCM node: ``value = mech(parents) * scale + noise``, then standardised."""

    parents: list[int]
    weights: np.ndarray
    # Mechanism-specific parameters (tanh slopes/offsets, interaction pairs).
    slopes: np.ndarray
    offsets: np.ndarray
    pairs: list[tuple[int, int]]
    pair_weights: np.ndarray
    noise_scale: float
    # Set by calibration: signal normalisation and output standardisation.
    signal_std: float = 1.0
    mean: float = 0.0
    std: float = 1.0


class Scene:
    """A sampled SCM with observed columns, roles and a thresholded outcome."""

    def __init__(self, family: int, seed: int) -> None:
        if family not in FAMILIES:
            raise ValueError(f"unknown family {family}")
        self.family = family
        self.seed = seed
        self.mechanism, self.noise_regime = FAMILIES[family]
        rng = np.random.default_rng([family, seed, 0])
        self._build_structure(rng)
        self._calibrate(np.random.default_rng([family, seed, 1]))

    # -- structure ---------------------------------------------------------------

    def _build_structure(self, rng: np.random.Generator) -> None:
        num_features = int(rng.integers(6, 16))
        num_groups = int(rng.choice([1, 2], p=[0.5, 0.5]))
        group_sizes = [int(rng.integers(2, 4)) for _ in range(num_groups)]
        # Leave room for at least 2 Markov-blanket and 1 irrelevant feature.
        num_features = max(num_features, sum(group_sizes) + 3)
        remaining = num_features - sum(group_sizes)
        num_irrelevant = int(rng.integers(1, max(2, remaining - 2) + 1))
        num_irrelevant = min(num_irrelevant, remaining - 2)
        num_mb = remaining - num_irrelevant
        num_children = int(rng.integers(0, min(2, num_mb - 1) + 1))
        num_parents = num_mb - num_children

        # Node order (topological): hidden causes, MB parents, z, MB children,
        # measurements, irrelevant features.
        nodes: list[_Node] = []
        kinds: list[tuple[str, int | None]] = []

        def add(kind: str, parents: list[int], group: int | None = None) -> int:
            nodes.append(self._make_node(rng, parents))
            kinds.append((kind, group))
            return len(nodes) - 1

        hidden = [add("hidden", [], g) for g in range(num_groups)]
        parents_idx: list[int] = []
        for _ in range(num_parents):
            # Random DAG among MB parents (no hidden-cause links, so the
            # measurement groups stay outside the Markov blanket of y).
            ups = [p for p in parents_idx if rng.random() < 0.3]
            parents_idx.append(add("parent", ups))
        z = add("z", parents_idx + hidden)
        children_idx = []
        for _ in range(num_children):
            spouse = [p for p in parents_idx if rng.random() < 0.3]
            children_idx.append(add("child", [z, *spouse]))
        measures_idx = []
        for g, size in enumerate(group_sizes):
            for _ in range(size):
                measures_idx.append(add("measure", [hidden[g]], g))
        irrelevant_idx: list[int] = []
        for _ in range(num_irrelevant):
            ups = [p for p in irrelevant_idx if rng.random() < 0.4]
            irrelevant_idx.append(add("irrelevant", ups))

        observed = parents_idx + children_idx + measures_idx + irrelevant_idx
        order = rng.permutation(len(observed))
        self._nodes = nodes
        self._z = z
        self._observed = [observed[i] for i in order]
        roles: list[ColumnRole] = []
        for node in self._observed:
            kind, group = kinds[node]
            if kind == "parent":
                roles.append(ColumnRole("mb", relation="parent"))
            elif kind == "child":
                roles.append(ColumnRole("mb", relation="child"))
            elif kind == "measure":
                roles.append(ColumnRole("measure", group=group))
            else:
                roles.append(ColumnRole("irrelevant"))
        self.roles: list[ColumnRole] = roles
        self.num_features = len(roles)
        self.num_groups = num_groups

    def _make_node(self, rng: np.random.Generator, parents: list[int]) -> _Node:
        k = len(parents)
        signs = rng.choice([-1.0, 1.0], size=k)
        weights = signs * rng.uniform(0.5, 1.5, size=k)
        pairs: list[tuple[int, int]] = []
        if self.mechanism == "interaction" and k >= 1:
            for _ in range(int(rng.integers(1, k + 1))):
                i, j = (int(v) for v in rng.integers(0, k, size=2))
                pairs.append((i, j))  # i == j gives a quadratic term
        pair_weights = rng.choice([-1.0, 1.0], size=len(pairs)) * rng.uniform(
            0.5, 1.5, size=len(pairs)
        )
        if k == 0:
            noise_scale = 1.0  # root: pure noise
        else:
            noise_scale = float(rng.uniform(0.3, 1.0))
        return _Node(
            parents=parents,
            weights=weights,
            slopes=rng.uniform(1.0, 3.0, size=k),
            offsets=rng.uniform(-1.0, 1.0, size=k),
            pairs=pairs,
            pair_weights=pair_weights,
            noise_scale=noise_scale,
        )

    # -- sampling ----------------------------------------------------------------

    def _noise(self, rng: np.random.Generator, n: int) -> np.ndarray:
        if self.noise_regime == "gaussian":
            return rng.standard_normal(n)
        # Heavy-tailed: Student-t with 3 dof, rescaled to unit variance.
        return rng.standard_t(3.0, size=n) / np.sqrt(3.0)

    def _signal(self, node: _Node, values: list[np.ndarray]) -> np.ndarray:
        xs = np.stack([values[p] for p in node.parents], axis=1)
        if self.mechanism == "linear":
            out = xs @ node.weights
        elif self.mechanism == "tanh":
            out = np.tanh(xs * node.slopes + node.offsets) @ node.weights
        else:  # interaction
            out = xs @ node.weights
            for (i, j), w in zip(node.pairs, node.pair_weights, strict=True):
                out = out + w * xs[:, i] * xs[:, j]
        return out

    def _forward(
        self, rng: np.random.Generator, n: int, *, calibrate: bool
    ) -> list[np.ndarray]:
        values: list[np.ndarray] = []
        for node in self._nodes:
            if node.parents:
                signal = self._signal(node, values)
                if calibrate:
                    s = signal.std()
                    node.signal_std = float(s) if s > 1e-8 else 1.0
                signal = signal / node.signal_std
                raw = signal + node.noise_scale * self._noise(rng, n)
            else:
                raw = self._noise(rng, n)
            if calibrate:
                node.mean = float(raw.mean())
                node.std = float(raw.std()) or 1.0
            values.append((raw - node.mean) / node.std)
        return values

    def _calibrate(self, rng: np.random.Generator) -> None:
        values = self._forward(rng, _CALIBRATION_ROWS, calibrate=True)
        # Base rate of y in [0.3, 0.7], so stratified n = 8 draws hold both classes.
        threshold_rng = np.random.default_rng([self.family, self.seed, 2])
        self.base_rate = float(threshold_rng.uniform(0.3, 0.7))
        self.threshold = float(np.quantile(values[self._z], 1.0 - self.base_rate))

    def sample(self, n: int, rng: np.random.Generator) -> tuple[np.ndarray, np.ndarray]:
        """Draw ``n`` rows: ``X`` (n, p) float32 and ``y`` (n,) int64 in {0, 1}."""
        values = self._forward(rng, n, calibrate=False)
        x = np.stack([values[i] for i in self._observed], axis=1).astype(np.float32)
        y = (values[self._z] > self.threshold).astype(np.int64)
        return x, y

    def describe(self) -> dict:
        """Role assignment and family metadata (input for stage-2 stories)."""
        return {
            "family": self.family,
            "seed": self.seed,
            "mechanism": self.mechanism,
            "noise_regime": self.noise_regime,
            "num_features": self.num_features,
            "base_rate": self.base_rate,
            "roles": [dataclasses.asdict(r) for r in self.roles],
        }
